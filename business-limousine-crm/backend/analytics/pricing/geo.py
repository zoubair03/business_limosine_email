def fit_road_factor():
    g = np.array([gc_km(a, b) for a, b, _ in CALIB])
    r = np.array([float(k) for _, _, k in CALIB])
    A = np.vstack([g, np.ones_like(g)]).T
    (m, c), *_ = np.linalg.lstsq(A, r, rcond=None)
    pred = m * g + c
    mape = np.mean(np.abs(pred - r) / r) * 100
    return m, c, mape, g, r, pred


ROAD_M, ROAD_C, _, _, _, _ = fit_road_factor()


def road_km(a, b):
    return max(ROAD_M * gc_km(a, b) + ROAD_C, 0.0)


