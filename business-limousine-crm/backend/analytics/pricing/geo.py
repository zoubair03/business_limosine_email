_PC_RE = re.compile(r"\b([1-9]\d{3})\s+[A-Za-zÀ-ÿ]")
_PC_ANY = re.compile(r"\b([1-9]\d{3})\b")

# Flight / train metadata is appended to the address by Waynium and carries foreign
# city names ("Terminal  Frankfurt 10:35") that must not be read as the destination.
_META = re.compile(r"\s*,?\s*(n[°ºo]\s*vol|num[eé]ro de train|terminal|vol heure|train)\b.*$", re.I | re.S)
# Non-Belgian addresses: the 4-digit code is not a Belgian postcode. Anchored to the end of
# the string, because Waynium writes the country last — "Place du Luxembourg, 1050 Bruxelles,
# Belgique" is a Brussels address, not a Luxembourg one.
_FOREIGN = re.compile(r",\s*(pays.?bas|nederland|the netherlands|netherlands|france|deutschland|"
                      r"allemagne|germany|luxembourg|royaume.?uni|united kingdom|suisse|"
                      r"switzerland|espagne|spain|italie|italy|autriche|austria)\s*\.?\s*$", re.I)
_NL_PC = re.compile(r"\b\d{4}\s*[A-Z]{2}\b")


def strip_meta(text):
    return _META.sub("", text or "").strip(" ,")


def geocode(text):
    """(lat, lon, how) or None."""
    if not text:
        return None
    t = strip_meta(text)
    if not t:
        t = text
    for rx, ll in AIRPORTS:
        if rx.search(t):
            return (ll[0], ll[1], "airport")
    for rx, ll in STATIONS:
        if rx.search(t):
            return (ll[0], ll[1], "station")
    foreign = bool(_FOREIGN.search(t)) or bool(_NL_PC.search(t))
    if not foreign:
        m = _PC_RE.findall(t) or _PC_ANY.findall(t)
        if m:
            code = m[-1]
            if code in PC:
                return (PC[code][0], PC[code][1], "postcode")
            if code[:2] in PREFIX:
                ll = PREFIX[code[:2]]
                return (ll[0], ll[1], "prefix")
    for rx, ll in CITIES:
        if rx.search(t):
            return (ll[0], ll[1], "city")
    return None


def gc_km(a, b):
    R = 6371.0088
    p1, p2 = np.radians(a[0]), np.radians(b[0])
    dp = p2 - p1
    dl = np.radians(b[1] - a[1])
    h = np.sin(dp / 2) ** 2 + np.cos(p1) * np.cos(p2) * np.sin(dl / 2) ** 2
    return 2 * R * np.arcsin(np.sqrt(h))


